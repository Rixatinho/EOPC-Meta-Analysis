# ==============================================================================
# Helper: copy with overwrite + verification
# ==============================================================================
safe_copy <- function(from, to, label = "") {
  if (!file.exists(from)) {
    cat("  [SKIP]", label, "- source not found:", basename(from), "\n")
    return(FALSE)
  }
  file.copy(from, to, overwrite = TRUE)
  if (file.exists(to)) {
    cat("  [OK]  ", label, "->", basename(to), "\n")
    return(TRUE)
  } else {
    cat("  [FAIL]", label, "- copy failed\n")
    return(FALSE)
  }
}

